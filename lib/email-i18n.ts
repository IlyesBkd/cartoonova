/* Les langues dans lesquelles les e-mails transactionnels existent. Elle est
   exportee parce qu'elle etait recopiee en dur dans la route de
   desinscription : deux listes pour la meme chose finissent par diverger, et
   ici c'est un client qui recevrait la mauvaise langue. */
export const LANGS = ["fr", "en", "es", "de", "it", "nl", "pl", "sv", "da", "pt"] as const;

export type Lang = (typeof LANGS)[number];

// Country code → language mapping
const countryToLang: Record<string, Lang>= {
 // French
 FR: "fr", MC: "fr", BE: "fr", LU: "fr", CH: "fr",
 // Spanish
 ES: "es", MX: "es", AR: "es", CO: "es", CL: "es", PE: "es", VE: "es",
 EC: "es", GT: "es", CU: "es", BO: "es", DO: "es", HN: "es", PY: "es",
 SV: "es", NI: "es", CR: "es", PA: "es", UY: "es",
 // German
 DE: "de", AT: "de",
 // Italian
 IT: "it", SM: "it", VA: "it",
 // English (default)
 US: "en", GB: "en", CA: "en", AU: "en", NZ: "en", IE: "en", ZA: "en",
 IN: "en", SG: "en", PH: "en", NG: "en", KE: "en",
 // Langues de la vague 1, desormais traduites : chaque pays recoit ses
 // e-mails dans sa langue.
 NL: "nl",
 PL: "pl",
 SE: "sv",
 DK: "da",
 PT: "pt",
};

export function getLangFromCountry(country: string | null | undefined): Lang {
 if (!country) return "fr";
 return countryToLang[country.toUpperCase()] || "en";
}

