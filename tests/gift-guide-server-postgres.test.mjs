test('bounded journals and cross-session payment uniqueness hold under real SQL concurrency',async()=>{
 const {createGiftGuideStore}=require('../lib/giftGuideServer.ts');const store=createGiftGuideStore(db);
 const a=await store.enroll(true),b=await store.enroll(true);
 const results=await Promise.all([store.attach(a.token,true,async()=> 'pi_unique'),store.attach(b.token,true,async()=> 'pi_unique')]);
 assert.equal(results.filter(Boolean).length,1);
 await db`UPDATE gift_guide_preparation.sessions SET cohort='guided-v1' WHERE session_id=${a.sessionId}`;
 await Promise.all(Array.from({length:10},()=>store.record(a.token,'exposed',true)));
 assert.deepEqual((await store.journal(a.token)).events,['exposed']);
 assert.equal(await store.record(a.token,'private@example.invalid',true),false);
 await db`DELETE FROM gift_guide_preparation.checkouts`;
 await db`INSERT INTO gift_guide_preparation.checkouts SELECT 'pi_limit' || i::text, token_hash FROM gift_guide_preparation.sessions CROSS JOIN generate_series(1,100) i WHERE session_id=${a.sessionId}`;
 assert.equal(await store.attach(a.token,true,async()=> 'pi_overflow'),false);
 assert.equal((await store.journal(a.token)).checkouts.length,100);
 await db`TRUNCATE gift_guide_preparation.sessions CASCADE`;
 await db`INSERT INTO gift_guide_preparation.sessions(token_hash,session_id,cohort) SELECT lpad(to_hex(i),64,'0'),md5(i::text)::uuid,'control' FROM generate_series(1,100000) i`;
 assert.equal(await store.enroll(true),null);
 await db`TRUNCATE gift_guide_preparation.sessions CASCADE`;
});
